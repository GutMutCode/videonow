#!/usr/bin/env python3
"""Compare the parameters engine commands are really given (by the engines' own tests) with their
parameter docs, and write `crates/videonow-core/src/params_extra.rs` and `docs/params-audit.md`.

Usage:
    VIDEONOW_PARAM_AUDIT=/tmp/audit.tsv cargo test -p filmcraft-engine -p photocraft-engine
    ./target/debug/videonow exec studio:commands '{}' > /tmp/commands.json
    scripts/params-audit.py /tmp/audit.tsv /tmp/commands.json

The audit file has one `id<TAB>key,key,...` line per command run (FilmCraft ids and PhotoCraft
ids; the engine is told apart by which registry has the id).
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

UNIVERSAL = {"image": {"coalesce", "target"}, "timeline": set()}


def documented_keys(doc: str):
    """Port of videonow_core::params::documented_keys (None = open-ended)."""
    depth, in_str, start = 0, False, 0
    quoted = []
    i = 0
    while i < len(doc):
        ch = doc[i]
        if in_str:
            if ch == '"':
                in_str = False
                quoted.append((start, i))
            i += 1
            continue
        if ch == '"':
            in_str = True
            start = i + 1
        elif ch in "{[":
            depth += 1
        elif ch in "}]":
            depth = max(0, depth - 1)
        if depth == 1 and (doc[i:].startswith("…") or doc[i:].startswith("...")) and doc[:i].lstrip().startswith("{"):
            return None
        i += 1
    if not doc.lstrip().startswith("{"):
        return None
    keys = []
    for n, (a, b) in enumerate(quoted):
        word = doc[a:b]
        if not word or not all(c.isascii() and (c.isalnum() or c == "_") for c in word):
            continue
        end, k = b + 1, n
        while True:
            rest = doc[end:]
            if rest.startswith(":"):
                keys.append(word)
                break
            if not rest.startswith(","):
                break
            if k + 1 >= len(quoted):
                break
            na, nb = quoted[k + 1]
            if na != end + 2 or not rest[1:].startswith('"'):
                break
            end, k = nb + 1, k + 1
    return keys


def main():
    audit_path, commands_path = sys.argv[1], sys.argv[2]
    root = Path(__file__).resolve().parent.parent
    cmds = json.loads(Path(commands_path).read_text())
    cmds = cmds.get("result", cmds)
    by_local = defaultdict(list)  # local id -> [(domain, doc)]
    for c in cmds:
        if c["domain"] in ("timeline", "image"):
            by_local[c["id"].split(":", 1)[1]].append((c["domain"], c["params"]))
    used = defaultdict(set)  # (domain, id) -> keys seen
    runs = defaultdict(int)
    for line in Path(audit_path).read_text(errors="replace").splitlines():
        if "\t" not in line:
            continue
        cid, keys = line.split("\t", 1)
        for domain, _doc in by_local.get(cid, []):
            runs[(domain, cid)] += 1
            used[(domain, cid)].update(k for k in keys.split(",") if k)
    extra = {}
    stats = defaultdict(lambda: defaultdict(int))
    for local, entries in by_local.items():
        for domain, doc in entries:
            st = stats[domain]
            st["commands"] += 1
            keys = documented_keys(doc)
            if keys is None:
                st["open"] += 1
                continue
            st["closed"] += 1
            if runs[(domain, local)]:
                st["exercised"] += 1
            missing = sorted(used[(domain, local)] - set(keys) - UNIVERSAL[domain])
            if missing:
                # the same id in both engines would be ambiguous; the audit can't tell them apart
                if len(entries) > 1:
                    st["ambiguous"] += 1
                    continue
                extra[f"{domain}:{local}"] = missing
                st["undocumented"] += 1
    lines = [
        "//! Generated by `scripts/params-audit.py` from the engines' test suites: parameters each command",
        "//! reads that its parameter doc does not name. Do not edit by hand; re-run the audit.",
        "",
        "pub const EXTRA: &[(&str, &[&str])] = &[",
    ]
    for k in sorted(extra):
        lines.append(f'    ("{k}", &[{", ".join(json.dumps(x) for x in extra[k])}]),')
    lines.append("];")
    (root / "crates/videonow-core/src/params_extra.rs").write_text("\n".join(lines) + "\n")
    report = ["# Parameter audit", "",
              "Engine commands whose parameter doc names its keys are checked strictly: an unknown key is refused",
              "before the command runs. The audit runs the engines' own test suites with `VIDEONOW_PARAM_AUDIT` set",
              "and lists keys the tests pass that the docs leave out; those are accepted too (`also_accepts` in",
              "`studio:commands`). Generated by `scripts/params-audit.py`.", "",
              "| Engine | Commands | Docs listing their keys (checked) | Open docs (not checked) | Checked commands the tests run | Commands with keys their doc leaves out |",
              "| --- | --- | --- | --- | --- | --- |"]
    for domain in ("timeline", "image"):
        st = stats[domain]
        report.append(f"| `{domain}:` | {st['commands']} | {st['closed']} | {st['open']} | {st['exercised']} | {st['undocumented']} |")
    report += ["", "`motion:` commands (EffectCraft) refuse unknown keys in the engine itself and are not audited here.", "",
               "## Keys the docs leave out", "", "| Command | Keys |", "| --- | --- |"]
    for k in sorted(extra):
        report.append(f"| `{k}` | {', '.join('`'+x+'`' for x in extra[k])} |")
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs/params-audit.md").write_text("\n".join(report) + "\n")
    for domain in ("timeline", "image"):
        print(domain, dict(stats[domain]))
    print(len(extra), "commands with undocumented keys")


if __name__ == "__main__":
    main()
